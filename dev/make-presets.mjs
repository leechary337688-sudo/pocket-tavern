function resetUid() { uid = 0; }
function e(comment, key, content, opts = {}) {
  uid += 1;
  return {
    uid,
    key: Array.isArray(key) ? key : [key],
    keysecondary: opts.keysecondary || [],
    comment,
    content,
    position: opts.position || 'before',
    order: opts.order ?? uid * 10,
    tokenBudget: opts.tokenBudget || 0,
    recursive: Boolean(opts.recursive),
    selective: Boolean(opts.selective),
    constant: Boolean(opts.constant),
    probability: opts.probability ?? 100,
    caseSensitive: Boolean(opts.caseSensitive),
    useRegex: Boolean(opts.useRegex),
    enabled: opts.enabled !== false,
  };
}
