import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
process.env.NODE_PATH = 'C:/Users/石晓佳/.dsh/profiles/desktop/node_modules';
require('module').Module._initPaths();
const { chromium } = require('playwright-core');
const BASE = process.env.PT_BASE || 'http://127.0.0.1:8788/';
const EXE = 'C:/Users/石晓佳/AppData/Local/ms-playwright/chromium-1223/chrome-win64/chrome.exe';
const browser = await chromium.launch({ executablePath: EXE });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2, serviceWorkers: 'block' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(String(e.stack || e)));
const checks = [];
const check = (name, ok, detail = '') => { checks.push({ name, ok }); console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${detail ? ' — ' + detail : ''}`); };
const sleep = (ms) => page.waitForTimeout(ms);
await page.goto(BASE);
await sleep(500);
await page.evaluate(async () => {
  const { Repo } = await import('/src/data/repo.js');
  const repo = new Repo(); await repo.init();
  await repo.saveSettings({ ageAck: true, onboardingDone: true, nsfw: false });
});
await page.reload();
await sleep(700);
await page.evaluate(() => { location.hash = '#/home'; });
await sleep(400);
await page.locator('button[aria-label="设置"]').click();
await sleep(500);
const presetBtn = page.getByRole('button', { name: /载入预设世界/ });
check('设置里有载入预设入口', await presetBtn.count() > 0);
await presetBtn.click();
await sleep(500);
const text = await page.locator('.overlay.is-open').innerText();
check('预设选择器有两套世界', text.includes('雾港夜雨') && text.includes('凤阙春深'), text.slice(0, 180));
await page.screenshot({ path: 'dev/preset-picker.png' });
const fogCard = page.locator('.preset-card').filter({ hasText: '雾港夜雨' });
await fogCard.getByRole('button', { name: /载入/ }).click();
await sleep(1500);
const body = await page.locator('body').innerText();
check('载入完成提示', body.includes('已摆上桌') || body.includes('已就绪'), body.slice(-300));
const counts = await page.evaluate(async () => {
  const { Repo } = await import('/src/data/repo.js');
  const repo = new Repo(); await repo.init();
  return { stats: await repo.stats(), quick: repo.settings.quickReplies?.length || 0 };
});
check('载入写库 12 卡 + 主书', counts.stats.cards === 13 && counts.stats.worlds >= 14, JSON.stringify(counts));
check('快捷回复 +4', counts.quick === 7, String(counts.quick));
check('无 pageerror', errors.length === 0, errors.join('\n'));
const failed = checks.filter((c) => !c.ok);
console.log(`${failed.length ? 'PRESET UI FAIL' : 'PRESET UI OK'} (${checks.length - failed.length}/${checks.length})`);
await browser.close();
if (failed.length) process.exit(1);
